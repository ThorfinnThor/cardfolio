const quoted = (value: string) => `“${value}”`;
const cards = (count: string) => `${count} ${count === "1" ? "card" : "cards"}`;
const subjects = (names: string) => names.replace(/ und /g, " and ");

const ERA_NOTE = "Es gibt nicht genug (alte|moderne) Karten\\. Den Rest haben wir mit (neueren|älteren) Karten aufgefüllt\\.";
const eraNote = (wished?: string, filler?: string) =>
  `There are not enough ${wished === "alte" ? "old" : "modern"} cards. We filled the rest with ${filler === "neueren" ? "newer" : "older"} cards.`;

